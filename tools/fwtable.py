#!/usr/bin/env python3
"""Generate TopazModem's firmware tables from a modem partition image (FAT16).

  fwtable.py MODEM_A.img > tables.inc

TopazModem reads firmware files straight from modem_a at fixed byte offsets
(no FAT driver in the kernel). This prints, for the given image:

  fw_files[]  image/modem.* as { name, off, size, crc32 } (one contiguous run each)
  fw_ext[]    every file's contiguous runs as { off, len }
  fw_all[]    every file as { path, size, first run, run count }

Paths are lower case and relative to the volume root, as the modem asks for
them over TFTP (Android mounts this volume with shortname=lower).
"""
import struct, sys, zlib


def read_fat16(img):
    bps, spc, rsvd, nfats, nroot, tot16, _media, spf = struct.unpack_from('<HBHBHHBH', img, 11)
    tot = tot16 or struct.unpack_from('<I', img, 32)[0]
    assert bps and spc and spf, 'not a FAT volume'
    cluster = bps * spc
    fat_off = rsvd * bps
    root_off = fat_off + nfats * spf * bps
    data_off = root_off + ((nroot * 32 + bps - 1) // bps) * bps
    nclusters = (tot * bps - data_off) // cluster
    assert nclusters < 65525, 'FAT32 is not supported'
    fat = struct.unpack_from(f'<{spf * bps // 2}H', img, fat_off)

    def chain(c):
        out = []
        while 2 <= c < 0xfff8:
            out.append(c)
            c = fat[c]
        return out

    def entries(buf):
        lfn = {}
        for i in range(0, len(buf), 32):
            e = buf[i:i + 32]
            if e[0] == 0:
                break
            if e[0] == 0xe5:
                lfn = {}
                continue
            attr = e[11]
            if attr == 0x0f:
                seq = e[0] & 0x1f
                part = (e[1:11] + e[14:26] + e[28:32]).decode('utf-16le', 'replace')
                lfn[seq] = part.split('\0')[0].rstrip('￿')
                continue
            if attr & 0x08:
                lfn = {}
                continue
            if lfn:
                name = ''.join(lfn[k] for k in sorted(lfn))
            else:
                base = e[0:8].decode('ascii', 'replace').rstrip()
                ext = e[8:11].decode('ascii', 'replace').rstrip()
                name = base + ('.' + ext if ext else '')
            lfn = {}
            if name in ('.', '..'):
                continue
            first = struct.unpack_from('<H', e, 26)[0]
            size = struct.unpack_from('<I', e, 28)[0]
            yield name, attr, first, size

    def cluster_bytes(c):
        o = data_off + (c - 2) * cluster
        return img[o:o + cluster]

    files = []

    def walk(buf, prefix):
        for name, attr, first, size in entries(buf):
            path = (prefix + name).lower()
            if attr & 0x10:
                walk(b''.join(cluster_bytes(c) for c in chain(first)), path + '/')
                continue
            runs, left = [], size
            for c in chain(first) if size else []:
                o = data_off + (c - 2) * cluster
                n = min(cluster, left)
                if runs and runs[-1][0] + runs[-1][1] == o:
                    runs[-1][1] += n
                else:
                    runs.append([o, n])
                left -= n
                if not left:
                    break
            assert left == 0, f'{path}: cluster chain shorter than the file'
            files.append((path, size, runs))

    walk(img[root_off:data_off], '')
    return files


def main():
    img = open(sys.argv[1], 'rb').read()
    files = sorted(read_fat16(img))
    ext, rows = [], []
    for path, size, runs in files:
        rows.append((path, size, len(ext), len(runs)))
        ext.extend(runs)
    modem = [(p, s, r) for p, s, r in files if p.startswith('image/modem.') and (p.endswith('.mdt') or p[-4:-2] == '.b')]
    print(f'/* generated by tools/fwtable.py from {sys.argv[1].rsplit("/", 1)[-1]}: '
          f'{len(files)} files, {len(ext)} extents, {len(modem)} modem files */')
    print('#define FW_FILES_TABLE \\')
    for p, s, r in modem:
        assert len(r) == 1, f'{p}: not contiguous'
        crc = zlib.crc32(img[r[0][0]:r[0][0] + s]) & 0xffffffff
        print(f'\t{{ "{p[len("image/"):]}", {r[0][0]:#x}, {s:#x}, {crc:#010x} }}, \\')
    print('')
    print('#define FW_EXT_TABLE \\')
    for o, n in ext:
        print(f'\t{{ {o:#x}, {n:#x} }}, \\')
    print('')
    print('#define FW_ALL_TABLE \\')
    for p, s, first, count in rows:
        print(f'\t{{ "{p}", {s:#x}, {first}, {count} }}, \\')
    print('')


if __name__ == '__main__':
    main()
